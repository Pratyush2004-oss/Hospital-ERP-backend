import { createHmac, timingSafeEqual } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve, sep } from "node:path";
import {
  StorageObjectNotFoundError,
  StorageOperationError,
  type PutObjectInput,
  type SignedDownloadUrl,
  type SignedDownloadUrlInput,
  type StorageProvider,
} from "./storage.types.js";

/**
 * Filesystem adapter for private document storage.
 *
 * Files live under one configured directory that the HTTP server never serves
 * statically, with `0700` directories and `0600` files. Object names are
 * opaque keys generated by the document service, never client filenames.
 *
 * Downloads do not use the filesystem path directly. The adapter signs a
 * short-lived URL that points at the API's own download endpoint, so a stolen
 * key alone is not enough: the URL also needs a valid HMAC and an unexpired
 * timestamp, and the API still performs its authorization check first.
 */

const KEY_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._/-]{0,511}$/;
const DEFAULT_DOWNLOAD_PATH = "/api/v1/documents/download";

export interface LocalStorageOptions {
  /** Absolute directory that holds the objects. */
  readonly rootDirectory: string;
  /** Secret used to sign download URLs (32+ characters recommended). */
  readonly signingSecret: string;
  /** API path that a future download route serves. */
  readonly downloadPath?: string;
}

interface SignedRequestInput {
  readonly key: string;
  readonly expires: string;
  readonly signature: string;
  readonly fileName: string;
}

function isSafeKey(key: string): boolean {
  return (
    KEY_PATTERN.test(key) &&
    !key.includes("..") &&
    !key.includes("\\") &&
    !key.startsWith("/")
  );
}

export class LocalStorageProvider implements StorageProvider {
  readonly name = "local";
  readonly #rootDirectory: string;
  readonly #signingSecret: string;
  readonly #downloadPath: string;

  constructor(options: LocalStorageOptions) {
    const root = resolve(options.rootDirectory);

    if (!options.signingSecret || options.signingSecret.length < 16) {
      throw new Error("Local storage requires a signing secret of at least 16 characters");
    }

    // Defence in depth: refuse locations that are filesystem roots, the project
    // root itself, or any directory that a static file server typically exposes.
    const isFilesystemRoot = resolve(root, sep) === root;
    const segments = root.split(/[\\/]+/);
    const looksPublic = segments.some((segment) =>
      /^(public|public_html|static|assets|www)$/i.test(segment),
    );

    if (isFilesystemRoot || looksPublic) {
      throw new Error(
        "STORAGE_LOCAL_ROOT must be a private directory, not a filesystem root or a public/static directory",
      );
    }

    this.#rootDirectory = root;
    this.#signingSecret = options.signingSecret;
    this.#downloadPath = options.downloadPath ?? DEFAULT_DOWNLOAD_PATH;
  }

  get rootDirectory(): string {
    return this.#rootDirectory;
  }

  #resolveKey(key: string): string {
    if (!isSafeKey(key)) {
      throw new StorageOperationError("resolve", "Invalid storage key");
    }

    const target = resolve(this.#rootDirectory, key);

    if (target !== this.#rootDirectory && !target.startsWith(`${this.#rootDirectory}${sep}`)) {
      throw new StorageOperationError("resolve", "Invalid storage key");
    }

    return target;
  }

  #signatureFor(key: string, expires: string, fileName: string): string {
    return createHmac("sha256", this.#signingSecret)
      .update(`${key}\n${expires}\n${fileName}`)
      .digest("hex");
  }

  async putObject(input: PutObjectInput): Promise<void> {
    const target = this.#resolveKey(input.key);

    try {
      await mkdir(dirname(target), { recursive: true, mode: 0o700 });
      // `wx` makes an accidental key reuse fail instead of silently replacing
      // an existing patient document.
      await writeFile(target, input.body, { flag: "wx", mode: 0o600 });
    } catch (error) {
      const code = (error as { code?: string }).code;

      if (code === "EEXIST") {
        throw new StorageOperationError("putObject", "An object already exists at this key");
      }

      throw new StorageOperationError("putObject");
    }
  }

  async getObject(key: string): Promise<Buffer> {
    const target = this.#resolveKey(key);

    try {
      return await readFile(target);
    } catch (error) {
      if ((error as { code?: string }).code === "ENOENT") {
        throw new StorageObjectNotFoundError(this.name, key);
      }

      throw new StorageOperationError("getObject");
    }
  }

  /** Idempotent: a missing object is not an error. */
  async deleteObject(key: string): Promise<void> {
    const target = this.#resolveKey(key);

    try {
      await rm(target, { force: true });
    } catch {
      throw new StorageOperationError("deleteObject");
    }
  }

  async createSignedDownloadUrl(input: SignedDownloadUrlInput): Promise<SignedDownloadUrl> {
    const expiresAt = new Date(Date.now() + input.expiresInSeconds * 1_000);
    const expires = String(Math.floor(expiresAt.getTime() / 1_000));
    const signature = this.#signatureFor(input.key, expires, input.fileName);

    // Relative to the API: the browser resolves it against the API origin. The
    // key is part of the signed payload, exactly like an S3 presigned URL, and
    // the URL is useless once it expires.
    const query = new URLSearchParams({
      key: input.key,
      expires,
      signature,
      fileName: input.fileName,
    });

    return {
      url: `${this.#downloadPath}?${query.toString()}`,
      expiresAt,
      provider: this.name,
    };
  }

  /**
   * Verifies a signed local download request. Exposed now so the future HTTP
   * download route can validate without duplicating the signing rules.
   */
  verifySignedRequest(input: SignedRequestInput): boolean {
    const expires = Number(input.expires);

    if (!Number.isInteger(expires) || expires * 1_000 <= Date.now()) {
      return false;
    }

    if (!isSafeKey(input.key)) return false;

    const expected = Buffer.from(this.#signatureFor(input.key, input.expires, input.fileName));
    const received = Buffer.from(input.signature);

    if (expected.length !== received.length) return false;

    return timingSafeEqual(expected, received);
  }
}

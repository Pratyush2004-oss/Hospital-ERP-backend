import type { Response } from "express";

/**
 * Standard response envelopes.
 *
 * Success: `{ data, meta? }`
 * Error:   `{ error: { code, message, details?, requestId } }`
 *
 * Every helper reads the request id from the Pino HTTP middleware so clients can
 * quote it when reporting a problem, and so logs can be correlated with the
 * response the client actually received.
 */

export interface ApiSuccessMeta {
  readonly requestId?: string;
  readonly pagination?: {
    readonly page: number;
    readonly pageSize: number;
    readonly total: number;
    readonly totalPages: number;
  };
}

export interface ApiSuccessBody<T> {
  readonly data: T;
  readonly meta?: Record<string, unknown>;
}

export interface ApiErrorBody {
  readonly error: {
    readonly code: string;
    readonly message: string;
    readonly details?: unknown;
    readonly requestId?: string;
  };
}

/** Reads the id generated by `pino-http` (declared as a union by that package). */
export function getRequestId(res: Response): string | undefined {
  const id: unknown = res.req?.id;
  return typeof id === "string" ? id : undefined;
}

export function successBody<T>(
  res: Response,
  data: T,
  meta?: ApiSuccessMeta,
): ApiSuccessBody<T> {
  const requestId = getRequestId(res);
  const merged = {
    ...(requestId === undefined ? {} : { requestId }),
    ...meta,
  };

  return Object.keys(merged).length > 0 ? { data, meta: merged } : { data };
}

export function sendSuccess<T>(
  res: Response,
  data: T,
  statusCode = 200,
  meta?: ApiSuccessMeta,
): Response {
  return res.status(statusCode).json(successBody(res, data, meta));
}

export function sendCreated<T>(res: Response, data: T, meta?: ApiSuccessMeta): Response {
  return sendSuccess(res, data, 201, meta);
}

/** 204 responses must not carry a body, so no envelope is written. */
export function sendNoContent(res: Response): Response {
  return res.status(204).end();
}

export function errorBody(
  res: Response,
  code: string,
  message: string,
  details?: unknown,
): ApiErrorBody {
  const requestId = getRequestId(res);

  return {
    error: {
      code,
      message,
      ...(details === undefined ? {} : { details }),
      ...(requestId === undefined ? {} : { requestId }),
    },
  };
}
